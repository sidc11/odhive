pub use ini::IniError;

/// File name of the generated config inside the project folder.
pub const CONF_FILE: &str = "odoo.conf";
/// The section Odoo reads.
pub const OPTIONS_SECTION: &str = "options";
/// Replacement for secret values in previews and debug output.
pub const MASK: &str = "********";
/// Project data folder (Odoo `data_dir`), relative to the project folder.
pub const DATA_DIR: &str = "data";
/// Keys OdHive writes from the project model.
pub const GENERATED_KEYS: &[&str] = &["addons_path", "data_dir"];
/// Keys OdHive sets per instance on the command line, or owns itself.
pub const INSTANCE_KEYS: &[&str] = &[
    "http_port",
    "gevent_port",
    "longpolling_port",
    "db_name",
    "workers",
    "logfile",
];
/// Longest accepted option key.
pub const MAX_KEY_LEN: usize = 128;

const HEADER: &str = "; Generated by OdHive. Edit settings in odhive.toml or the OdHive UI;\n; changes made here are overwritten.\n";

/// Errors returned by the generator, importer and setters.
#[derive(Debug, Error)]
pub enum ConfError {
    /// The file is not valid `configparser` syntax.
    #[error(transparent)]
    Syntax(#[from] IniError),
    /// The file has no `[options]` section.
    #[error("no [options] section")]
    NoOptionsSection,
    /// A key with characters configparser or Odoo would not keep.
    #[error("invalid option key {0:?}")]
    BadKey(String),
    /// A value that cannot be written safely or fails the schema.
    #[error("invalid value for {key}: {reason}")]
    BadValue {
        /// Option key.
        key: String,
        /// Why it was rejected.
        reason: String,
    },
    /// The key is set by OdHive itself.
    #[error("{0} is managed by OdHive and cannot be set here")]
    Managed(String),
    /// The option cannot be read from a config file.
    #[error("{0} is a command-line only option")]
    NotFileLoadable(String),
    /// A section name that is not allowed.
    #[error("invalid section name {0:?}")]
    BadSection(String),
    /// A path that cannot be written into a comma-separated list.
    #[error("path {0:?} contains a comma or line break")]
    BadPath(PathBuf),
    /// Writing the file failed.
    #[error("{path}: {source}")]
    Io {
        /// Path involved.
        path: PathBuf,
        /// Underlying error.
        #[source]
        source: std::io::Error,
    },
}

/// Option key → raw value, as written in `odoo.conf`. Secrets are masked in `Debug`.
#[derive(Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(transparent)]
pub struct OdooOptions(pub BTreeMap<String, String>);

impl OdooOptions {
    /// Whether no options are set.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    /// Value of `key`, if set.
    #[must_use]
    pub fn get(&self, key: &str) -> Option<&str> {
        self.0.get(key).map(String::as_str)
    }
}

impl fmt::Debug for OdooOptions {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_map()
            .entries(self.0.iter().map(|(k, v)| (k, masked(k, v))))
            .finish()
    }
}

/// `MASK` for secret keys, the value otherwise.
#[must_use]
pub fn masked<'a>(key: &str, value: &'a str) -> &'a str {
    if is_secret(key) { MASK } else { value }
}

/// Whether `key` holds a secret.
#[must_use]
pub fn is_secret(key: &str) -> bool {
    SECRET_KEYS.contains(&key)
}

/// Whether OdHive sets `key` itself (generated or per-instance).
#[must_use]
pub fn is_managed_key(key: &str) -> bool {
    GENERATED_KEYS.contains(&key) || INSTANCE_KEYS.contains(&key)
}

/// Checks that a key is something configparser reads back unchanged.
///
/// # Errors
/// Returns [`ConfError::BadKey`].
pub fn validate_key(key: &str) -> Result<(), ConfError> {
    let ok = !key.is_empty()
        && key.len() <= MAX_KEY_LEN
        && key.bytes().all(|b| {
            b.is_ascii_lowercase() || b.is_ascii_digit() || matches!(b, b'_' | b'.' | b'-')
        });
    if ok {
        Ok(())
    } else {
        Err(ConfError::BadKey(key.to_owned()))
    }
}

/// Checks that a value can be written on one line and read back unchanged.
///
/// # Errors
/// Returns [`ConfError::BadValue`].
pub fn validate_value(key: &str, value: &str) -> Result<(), ConfError> {
    let reason = if value.contains(['\n', '\r', '\0']) {
        Some("contains a line break or NUL byte")
    } else if value != value.trim() {
        Some("has leading or trailing whitespace (configparser would strip it)")
    } else {
        None
    };
    match reason {
        Some(r) => Err(ConfError::BadValue {
            key: key.to_owned(),
            reason: r.to_owned(),
        }),
        None => Ok(()),
    }
}

/// Checks a section name for `[odoo_sections.*]`.
///
/// # Errors
/// Returns [`ConfError::BadSection`].
pub fn validate_section(name: &str) -> Result<(), ConfError> {
    let ok = !name.is_empty()
        && name.len() <= MAX_KEY_LEN
        && name != OPTIONS_SECTION
        && name != "DEFAULT"
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'_' | b'.' | b'-'));
    if ok {
        Ok(())
    } else {
        Err(ConfError::BadSection(name.to_owned()))
    }
}

/// Format checks for everything stored in the project model (no schema needed).
///
/// # Errors
/// Returns the first invalid key, value or section, or a managed key in `options`.
pub fn validate_model(
    options: &OdooOptions,
    sections: &BTreeMap<String, OdooOptions>,
) -> Result<(), ConfError> {
    for (k, v) in &options.0 {
        validate_key(k)?;
        if is_managed_key(k) {
            return Err(ConfError::Managed(k.clone()));
        }
        validate_value(k, v)?;
    }
    for (name, entries) in sections {
        validate_section(name)?;
        for (k, v) in &entries.0 {
            validate_key(k)?;
            validate_value(k, v)?;
        }
    }
    Ok(())
}

/// Checks `value` against the option's type the way Odoo parses it.
///
/// # Errors
/// Returns a human-readable reason.
pub fn check_value(option: &OdooOption, value: &str) -> Result<(), String> {
    if value == "None" {
        return Ok(()); // Odoo: "None" means unset for every type.
    }
    match &option.kind {
        OptionKind::Int => value
            .parse::<i64>()
            .map(drop)
            .map_err(|_| "expected an integer".to_owned()),
        OptionKind::Float => value
            .parse::<f64>()
            .map(drop)
            .map_err(|_| "expected a number".to_owned()),
        OptionKind::Bool => parse_bool(value)
            .map(drop)
            .ok_or_else(|| "expected true/false, yes/no, on/off or 1/0".to_owned()),
        OptionKind::Choice { choices } => {
            if choices.iter().any(|c| c == value) {
                Ok(())
            } else {
                Err(format!("expected one of {}", choices.join(", ")))
            }
        }
        OptionKind::String | OptionKind::Path | OptionKind::List => Ok(()),
    }
}

/// Odoo's `_check_bool`.
#[must_use]
pub fn parse_bool(value: &str) -> Option<bool> {
    match value.to_ascii_lowercase().as_str() {
        "1" | "yes" | "true" | "on" => Some(true),
        "0" | "no" | "false" | "off" => Some(false),
        _ => None,
    }
}

/// A default from the schema, formatted the way Odoo writes it.
#[must_use]
pub fn format_default(value: &Value) -> Option<String> {
    match value {
        Value::Null => None,
        Value::Bool(b) => Some(if *b { "True" } else { "False" }.to_owned()),
        Value::Number(n) => Some(n.to_string()),
        Value::String(s) => Some(s.clone()),
        Value::Array(items) => Some(
            items
                .iter()
                .filter_map(format_default)
                .filter(|s| !s.is_empty())
                .collect::<Vec<_>>()
                .join(","),
        ),
        Value::Object(_) => None,
    }
}

/// Sets an option after checking key, value and (when known) the schema type.
/// Options unknown to the schema are accepted: third-party modules read their own.
///
/// # Errors
/// Fails on invalid or managed keys, command-line only options and bad values.
pub fn set_option(
    options: &mut OdooOptions,
    schema: &OptionSchema,
    key: &str,
    value: &str,
) -> Result<(), ConfError> {
    validate_key(key)?;
    if is_managed_key(key) {
        return Err(ConfError::Managed(key.to_owned()));
    }
    validate_value(key, value)?;
    if let Some(opt) = schema.get(key) {
        if !opt.file_loadable {
            return Err(ConfError::NotFileLoadable(key.to_owned()));
        }
        check_value(opt, value).map_err(|reason| ConfError::BadValue {
            key: key.to_owned(),
            reason,
        })?;
    }
    options.0.insert(key.to_owned(), value.to_owned());
    Ok(())
}

/// Per-instance settings found in an imported file (applied to an instance by the caller).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct InstanceHints {
    /// `http_port`.
    pub http_port: Option<u16>,
    /// `gevent_port` (or the legacy `longpolling_port`).
    pub gevent_port: Option<u16>,
    /// `db_name`, when it names a single database.
    pub db: Option<String>,
    /// `workers`.
    pub workers: Option<u32>,
}

/// Result of [`import_conf`].
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ImportedConf {
    /// Options for `[odoo_options]` (defaults and managed keys removed).
    pub options: OdooOptions,
    /// Other sections for `[odoo_sections.*]`.
    pub sections: BTreeMap<String, OdooOptions>,
    /// Per-instance settings.
    pub instance: InstanceHints,
    /// Custom addons paths (Odoo and Enterprise source paths removed).
    pub addons_paths: Vec<PathBuf>,
    /// What was dropped or kept as-is, and why.
    pub warnings: Vec<String>,
}

/// Imports an existing `odoo.conf` into the project model.
///
/// Values Odoo itself would ignore or that OdHive manages are dropped with a
/// warning; values equal to the schema default are dropped silently (an `--save`d
/// file lists every option). `source_addons` are the addons folders of the
/// project's sources; they are regenerated and therefore not imported.
///
/// # Errors
/// Fails only on syntax errors or a missing `[options]` section.
pub fn import_conf(
    text: &str,
    schema: &OptionSchema,
    source_addons: &[PathBuf],
) -> Result<ImportedConf, ConfError> {
    let sections = ini::parse(text)?;
    let mut out = ImportedConf::default();
    let mut found = false;
    for (name, entries) in sections {
        if name == OPTIONS_SECTION {
            found = true;
            for (key, value) in entries {
                import_option(&mut out, schema, source_addons, key, value);
            }
            continue;
        }
        if validate_section(&name).is_err() {
            out.warnings
                .push(format!("section [{name}]: invalid name, skipped"));
            continue;
        }
        let mut kept = OdooOptions::default();
        for (key, value) in entries {
            match validate_key(&key).and_then(|()| validate_value(&key, &value)) {
                Ok(()) => {
                    kept.0.insert(key, value);
                }
                Err(e) => out.warnings.push(format!("[{name}] {e}, skipped")),
            }
        }
        out.sections.insert(name, kept);
    }
    if !found {
        return Err(ConfError::NoOptionsSection);
    }
    Ok(out)
}

fn import_option(
    out: &mut ImportedConf,
    schema: &OptionSchema,
    source_addons: &[PathBuf],
    mut key: String,
    mut value: String,
) {
    let warn = |out: &mut ImportedConf, msg: String| out.warnings.push(msg);
    let unset = value.is_empty() || value == "None" || value.eq_ignore_ascii_case("false");

    // Odoo: `without_demo` is stored inverted in `with_demo`.
    if key == "without_demo" {
        // Like `_check_without_demo`: a non-boolean (e.g. the pre-19 `all`) means
        // "no demo data" unless it is "None".
        let demo = match parse_bool(&value) {
            Some(b) => !b,
            None => {
                warn(
                    out,
                    format!(
                        "without_demo = {value:?}: not a boolean, read as {}",
                        value != "None"
                    ),
                );
                value == "None"
            }
        };
        key = "with_demo".into();
        value = if demo { "True" } else { "False" }.into();
    }

    match key.as_str() {
        "http_port" | "gevent_port" | "longpolling_port" => {
            if !unset {
                match value.parse::<u16>() {
                    Ok(p) if key == "http_port" => out.instance.http_port = Some(p),
                    Ok(p) => out.instance.gevent_port = Some(p),
                    Err(_) => warn(out, format!("{key} = {value:?}: not a port, skipped")),
                }
            }
            return;
        }
        "db_name" => {
            if !unset {
                if value.contains(',') {
                    warn(
                        out,
                        format!("db_name lists several databases ({value}); set one per instance"),
                    );
                } else {
                    out.instance.db = Some(value);
                }
            }
            return;
        }
        "workers" => {
            if !unset {
                match value.parse::<u32>() {
                    Ok(w) => out.instance.workers = Some(w),
                    Err(_) => warn(out, format!("workers = {value:?}: not a number, skipped")),
                }
            }
            return;
        }
        "addons_path" => {
            let normalize = |p: &Path| PathBuf::from(p.to_string_lossy().trim_end_matches('/'));
            let known: Vec<PathBuf> = source_addons.iter().map(|p| normalize(p)).collect();
            for part in value.split(',').map(str::trim).filter(|p| !p.is_empty()) {
                let path = normalize(Path::new(part));
                if !known.contains(&path) && !out.addons_paths.contains(&path) {
                    out.addons_paths.push(path);
                }
            }
            return;
        }
        "data_dir" | "logfile" => {
            if !unset && !value.is_empty() {
                warn(out, format!("{key} = {value}: managed by OdHive, ignored"));
            }
            return;
        }
        _ => {}
    }

    if let Err(e) = validate_key(&key) {
        warn(out, format!("{e}, skipped"));
        return;
    }
    let option = schema.get(&key);
    if let Some(opt) = option {
        if !opt.file_loadable {
            warn(out, format!("{key}: command-line only option, ignored"));
            return;
        }
        // Odoo skips "False" for non-boolean options (old `--save` files).
        if value.eq_ignore_ascii_case("false") && opt.kind != OptionKind::Bool {
            return;
        }
        if value.contains('\n') {
            if opt.kind == OptionKind::List {
                value = value
                    .split('\n')
                    .map(str::trim)
                    .collect::<Vec<_>>()
                    .concat();
            } else {
                warn(out, format!("{key}: multi-line value, skipped"));
                return;
            }
        }
        if let Err(reason) = check_value(opt, &value) {
            warn(
                out,
                format!("{key} = {}: {reason}, skipped", masked(&key, &value)),
            );
            return;
        }
        let default = opt.default.as_ref().and_then(format_default);
        let is_default = match default {
            Some(d) => d == value,
            // "None" on an option without a default is a no-op.
            None => value == "None",
        };
        if is_default {
            return;
        }
    } else {
        if let Err(e) = validate_value(&key, &value) {
            warn(out, format!("{e}, skipped"));
            return;
        }
        warn(
            out,
            format!("{key}: unknown to Odoo {}, kept as-is", schema.series),
        );
    }
    out.options.0.insert(key, value);
}

/// Everything the generator derives from the project and its sources.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConfContext {
    /// Full `addons_path`, in order.
    pub addons_paths: Vec<PathBuf>,
    /// Odoo `data_dir`.
    pub data_dir: PathBuf,
}

impl ConfContext {
    /// Addons path order: Community `addons`, Enterprise, then the project's own
    /// folders. (`odoo/addons` with `base` is added by Odoo itself.)
    #[must_use]
    pub fn for_project(
        project: &ProjectConfig,
        project_dir: &Path,
        community: &SourceEntry,
        enterprise: Option<&SourceEntry>,
    ) -> Self {
        let mut addons_paths = vec![community.path.join("addons")];
        addons_paths.extend(enterprise.map(|e| e.path.clone()));
        addons_paths.extend(project.resolved_addons_paths(project_dir));
        Self {
            addons_paths,
            data_dir: project_dir.join(DATA_DIR),
        }
    }

    /// Source addons folders, as passed to [`import_conf`].
    #[must_use]
    pub fn source_addons(
        community: &SourceEntry,
        enterprise: Option<&SourceEntry>,
    ) -> Vec<PathBuf> {
        let mut v = vec![
            community.path.join("addons"),
            community.path.join("odoo/addons"),
        ];
        v.extend(enterprise.map(|e| e.path.clone()));
        v
    }
}

/// Renders `odoo.conf`. With `mask`, secret values are replaced by [`MASK`] (for
/// previews and debug bundles; never write a masked file).
///
/// # Errors
/// Fails on a path that cannot be written into `addons_path`, or on an invalid
/// model (see [`validate_model`]).
pub fn render(
    ctx: &ConfContext,
    options: &OdooOptions,
    sections: &BTreeMap<String, OdooOptions>,
    schema: Option<&OptionSchema>,
    mask: bool,
) -> Result<String, ConfError> {
    validate_model(options, sections)?;
    let path_str = |p: &Path| {
        let s = p.to_string_lossy().into_owned();
        if s.contains([',', '\n', '\r']) {
            Err(ConfError::BadPath(p.to_path_buf()))
        } else {
            Ok(s)
        }
    };
    let addons = ctx
        .addons_paths
        .iter()
        .map(|p| path_str(p))
        .collect::<Result<Vec<_>, _>>()?
        .join(",");
    let data_dir = path_str(&ctx.data_dir)?;

    let show = |k: &str, v: &str| {
        if mask {
            masked(k, v).to_owned()
        } else {
            v.to_owned()
        }
    };
    let mut ordered: Vec<(String, String)> = vec![
        ("addons_path".into(), addons),
        ("data_dir".into(), data_dir),
    ];
    if let Some(schema) = schema {
        for opt in &schema.options {
            if let Some(v) = options.get(&opt.key) {
                ordered.push((opt.key.clone(), show(&opt.key, v)));
            }
        }
    }
    for (k, v) in &options.0 {
        if !ordered.iter().any(|(ok, _)| ok == k) {
            ordered.push((k.clone(), show(k, v)));
        }
    }

    let mut all: Vec<(&str, Vec<(&str, &str)>)> = vec![(
        OPTIONS_SECTION,
        ordered
            .iter()
            .map(|(k, v)| (k.as_str(), v.as_str()))
            .collect(),
    )];
    for (name, entries) in sections {
        all.push((
            name.as_str(),
            entries
                .0
                .iter()
                .map(|(k, v)| (k.as_str(), v.as_str()))
                .collect(),
        ));
    }
    Ok(format!("{HEADER}{}", ini::write(all)))
}

/// Renders the project's `odoo.conf` and writes it atomically with mode `0600`.
///
/// # Errors
/// See [`render`]; also I/O errors.
pub fn write_conf(
    project: &ProjectConfig,
    project_dir: &Path,
    ctx: &ConfContext,
    schema: Option<&OptionSchema>,
) -> Result<PathBuf, ConfError> {
    let text = render(
        ctx,
        &project.odoo_options,
        &project.odoo_sections,
        schema,
        false,
    )?;
    let path = project_dir.join(CONF_FILE);
    fsutil::write_private_atomic(&path, text.as_bytes()).map_err(|e| ConfError::Io {
        path: e.path,
        source: e.source,
    })?;
    Ok(path)
}

