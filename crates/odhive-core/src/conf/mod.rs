//! `odoo.conf` generator and importer.
//!
//! The project model (`odhive.toml`) is the source of truth: user-chosen Odoo
//! options live in `[odoo_options]` (and other sections in `[odoo_sections.*]`).
//! `odoo.conf` is generated from it, in a stable order:
//!
//! 1. keys OdHive derives from the project: `addons_path`, `data_dir`
//! 2. user options in the order of the Odoo option schema
//! 3. options unknown to the schema (e.g. read by third-party modules), sorted
//! 4. other sections, sorted (Odoo 20 reads `[colors]`; modules may read their own)
//!
//! Per-instance settings (`http_port`, `gevent_port`, `db_name`, `workers`) and the
//! log file are passed on the `odoo-bin` command line by the supervisor and never
//! written here. Secrets (`admin_passwd`, `db_password`, …) are masked in `Debug`
//! output and in previews rendered with `mask = true`.

pub mod ini;

use std::collections::BTreeMap;
use std::fmt;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use serde_json::Value;
use thiserror::Error;

